process.env.DATABASE_URL = ":memory:";

import { beforeAll, beforeEach, describe, expect, it } from "vitest";
import { eq } from "drizzle-orm";
import * as XLSX from "xlsx";
import { getDb } from "@/server/db";
import { ahAuditLogs, ahTeamMembers, ahTeams } from "@/server/db/schema";
import { verifyPassword } from "@/server/auth/password";
import {
  generateTeamPassword,
  parseRosterFile,
  importTeamsChunk,
  getEventTeamsForCredentials,
  MAX_TEAMS_PER_IMPORT_CHUNK,
  type ParsedTeamRow,
} from "./teams";
import { resetAlgoHuntTables, setupTestDb } from "./testing/db";
import { seedFixture } from "./testing/fixtures";

beforeAll(setupTestDb);
beforeEach(resetAlgoHuntTables);

describe("team password generator", () => {
  it("generates an 8-character string using unambiguous characters", () => {
    const pw = generateTeamPassword();
    expect(pw).toHaveLength(8);
    expect(/^[23456789abcdefghjkmnpqrstuvwxyz]{8}$/.test(pw)).toBe(true);
  });

  it("generates distinct passwords across invocations", () => {
    const set = new Set<string>();
    for (let i = 0; i < 20; i++) {
      set.add(generateTeamPassword());
    }
    expect(set.size).toBe(20);
  });
});

describe("roster file parser (CSV / XLSX)", () => {
  it("parses CSV content with various header casings", () => {
    const csvContent = `Team Name,College,Member 1 Name,Member 1 Email,Member 1 Phone,Member 2 Name\nAlpha Squad,PES University,Alice,alice@pes.edu,9876543210,Bob\nBeta Crew,BMSCE,Charlie,charlie@bms.edu,,David`;
    const buf = Buffer.from(csvContent, "utf-8");
    const parsed = parseRosterFile(buf);

    expect(parsed).toHaveLength(2);
    expect(parsed[0].teamName).toBe("Alpha Squad");
    expect(parsed[0].college).toBe("PES University");
    expect(parsed[0].members).toHaveLength(2);
    expect(parsed[0].members[0].name).toBe("Alice");
    expect(parsed[0].members[0].isCaptain).toBe(true);
    expect(parsed[0].members[1].name).toBe("Bob");

    expect(parsed[1].teamName).toBe("Beta Crew");
    expect(parsed[1].members).toHaveLength(2);
    expect(parsed[1].members[0].name).toBe("Charlie");
    expect(parsed[1].members[1].name).toBe("David");
  });

  it("parses XLSX buffers generated by SheetJS", () => {
    const wb = XLSX.utils.book_new();
    const ws = XLSX.utils.aoa_to_sheet([
      ["Team", "Institution", "Captain", "Player 2", "Player 3", "Player 4"],
      ["CodeMonks", "RVCE", "Sunil", "Rahul", "Priya", "Amit"],
    ]);
    XLSX.utils.book_append_sheet(wb, ws, "Teams");
    const xlsxBuf = XLSX.write(wb, { type: "buffer", bookType: "xlsx" });

    const parsed = parseRosterFile(xlsxBuf);
    expect(parsed).toHaveLength(1);
    expect(parsed[0].teamName).toBe("CodeMonks");
    expect(parsed[0].college).toBe("RVCE");
    expect(parsed[0].members).toHaveLength(4);
    expect(parsed[0].members[0].name).toBe("Sunil");
    expect(parsed[0].members[0].isCaptain).toBe(true);
    expect(parsed[0].members[3].name).toBe("Amit");
  });

  it("handles fallback when only team name is provided", () => {
    const csv = `Team Name\nLone Wolf`;
    const parsed = parseRosterFile(Buffer.from(csv));
    expect(parsed).toHaveLength(1);
    expect(parsed[0].teamName).toBe("Lone Wolf");
    expect(parsed[0].members).toHaveLength(1);
    expect(parsed[0].members[0].name).toBe("Lone Wolf");
  });
});

describe("chunked team import (Cloudflare Workers bounds)", () => {
  it("rejects chunks exceeding MAX_TEAMS_PER_IMPORT_CHUNK", async () => {
    const fixture = await seedFixture({ codes: 0, teams: 0 });
    const teams: ParsedTeamRow[] = Array.from({ length: MAX_TEAMS_PER_IMPORT_CHUNK + 1 }, (_, i) => ({
      teamName: `Team ${i}`,
      members: [{ name: `Member ${i}`, isCaptain: true }],
    }));

    const result = await importTeamsChunk({
      eventId: fixture.event.id,
      teams,
    });

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.code).toBe("VALIDATION");
  });

  it("imports a valid batch of teams, hashes passwords, and logs an audit", async () => {
    const fixture = await seedFixture({ codes: 0, teams: 0 });
    const teams: ParsedTeamRow[] = [
      {
        teamName: "Cipher Warriors",
        college: "PESU",
        members: [
          { name: "John", email: "john@example.com", isCaptain: true },
          { name: "Jane", email: "jane@example.com" },
        ],
      },
      {
        teamName: "Binary Bosses",
        college: "PESU",
        members: [{ name: "Alex", isCaptain: true }],
      },
    ];

    const result = await importTeamsChunk({
      eventId: fixture.event.id,
      teams,
      startingIndex: 1,
      actorId: "admin-roster",
    });

    expect(result.ok).toBe(true);
    if (!result.ok) return;

    expect(result.imported).toHaveLength(2);
    expect(result.imported[0].teamCode).toMatch(/^TST-001|AH2-001/);
    expect(result.imported[1].teamCode).toMatch(/^TST-002|AH2-002/);
    expect(result.nextIndex).toBe(3);

    // Verify plain password is valid against hashed password in DB
    const [teamRow] = await getDb()
      .select()
      .from(ahTeams)
      .where(eq(ahTeams.id, result.imported[0].id));
    expect(teamRow).toBeDefined();

    const isMatch = await verifyPassword(result.imported[0].plainPassword, teamRow.passwordHash);
    expect(isMatch.ok).toBe(true);

    // Verify members are stored in ahTeamMembers
    const memberRows = await getDb()
      .select()
      .from(ahTeamMembers)
      .where(eq(ahTeamMembers.teamId, result.imported[0].id));
    expect(memberRows).toHaveLength(2);

    // Verify audit log recorded
    const audits = await getDb()
      .select()
      .from(ahAuditLogs)
      .where(eq(ahAuditLogs.action, "import.teams"));
    expect(audits).toHaveLength(1);
    expect(audits[0].actorId).toBe("admin-roster");
  });

  it("fetches credentials and members for printing slips", async () => {
    const fixture = await seedFixture({ codes: 0, teams: 0 });
    await importTeamsChunk({
      eventId: fixture.event.id,
      teams: [
        {
          teamName: "Slip Team",
          college: "Campus A",
          members: [{ name: "Player 1", isCaptain: true }, { name: "Player 2" }],
        },
      ],
    });

    const forCreds = await getEventTeamsForCredentials(fixture.event.id);
    expect(forCreds).toHaveLength(1);
    expect(forCreds[0].teamName).toBe("Slip Team");
    expect(forCreds[0].members).toHaveLength(2);
  });
});
